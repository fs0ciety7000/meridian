import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';

/**
 * Offline play (architecture §PWA, development-plan 3.1): after the build, emits `sw.js` with
 * the exact list of files to precache — app shell, fonts, textures, geography, facts and every
 * prompt library — and a version derived from that list, so a new deploy replaces the cache.
 * Kept in-house: ~60 lines instead of a Workbox toolchain.
 */
export function pwa(): Plugin {
  return {
    name: 'meridian-pwa',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle)
        .filter((f) => !f.endsWith('.map') && f !== 'sw.js')
        // Lab pages are development tools: not worth a byte of the player's storage.
        .filter((f) => !/\/(MapLab|Specimen)-/.test(f))
        // Fonts: every browser we target reads woff2, and the game is written in Latin scripts.
        .filter((f) => !/\.(woff2?)$/.test(f) || (/\.woff2$/.test(f) && /-latin(-ext)?-/.test(f)))
        .map((f) => `/${f}`);
      const publicFiles = [
        '/favicon.svg',
        '/manifest.webmanifest',
        '/theme-init.js',
        '/icons/icon-192.png',
        '/icons/icon-512.png',
        '/icons/apple-touch-icon.png',
      ];
      const precache = ['/', ...publicFiles, ...files.filter((f) => f !== '/index.html')].sort();
      const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, precache) });
    },
  };
}

function serviceWorker(version: string, precache: string[]): string {
  return `// Generated by apps/web/scripts/pwa-plugin.ts — do not edit.
const CACHE = 'meridian-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('meridian-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin || url.pathname.startsWith('/api/')) return;
  if (req.mode === 'navigate') {
    // Network first for the HTML shell (fresh deploys), cached shell offline: every route is
    // a client-side route (/x/MER-…, /passeport).
    event.respondWith(fetch(req).catch(() => caches.match('/', { ignoreSearch: true })));
    return;
  }
  // Hashed assets and content: cache first, then network (and remember it).
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && url.pathname.startsWith('/assets/')) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
}
