import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens } from '../src/index';

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../dist/tokens.css');

const block = (vars: Record<string, string | number>) =>
  Object.entries(vars)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n');

const color = (theme: Record<string, string>) =>
  block(Object.fromEntries(Object.entries(theme).map(([k, v]) => [`color-${k}`, v])));

const statics: Record<string, string | number> = {};
for (const [k, v] of Object.entries(tokens.font)) statics[`font-${k}`] = v;
for (const [k, v] of Object.entries(tokens.type)) {
  statics[`type-${k}-size`] = v.size;
  statics[`type-${k}-line`] = v.line;
  if ('tracking' in v) statics[`type-${k}-tracking`] = v.tracking;
}
for (const [k, v] of Object.entries(tokens.space)) statics[`space-${k}`] = v;
for (const [k, v] of Object.entries(tokens.radius)) statics[`radius-${k}`] = v;
for (const [k, v] of Object.entries(tokens.shadow)) statics[`shadow-${k}`] = v;
statics['material-brass'] = `linear-gradient(180deg, ${tokens.material.brass.stops
  .map(([color, at]) => `${color} ${Number(at) * 100}%`)
  .join(', ')})`;
statics['material-brass-ink'] = tokens.material.brassInk;
for (const [k, v] of Object.entries(tokens.motion.ease)) statics[`ease-${k}`] = v;
for (const [k, v] of Object.entries(tokens.motion.duration)) statics[`dur-${k}`] = `${v}ms`;

const css = `/* Generated by packages/design-tokens/scripts/build-css.ts — do not edit. */
:root {
${block(statics)}
${color(tokens.themes.atlas)}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='atlas']) {
${color(tokens.themes.nocturne)}
    color-scheme: dark;
  }
}

:root[data-theme='nocturne'] {
${color(tokens.themes.nocturne)}
  color-scheme: dark;
}

@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion='full']) {
${block(Object.fromEntries(Object.keys(tokens.motion.duration).map((k) => [`dur-${k}`, '0ms'])))}
  }
}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens.css written (${css.length} bytes)`);
